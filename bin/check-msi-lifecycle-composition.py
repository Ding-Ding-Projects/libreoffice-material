#!/usr/bin/env python3
"""Fail-closed Material branding and lifecycle contract for the Windows MSI UI."""

from __future__ import annotations

import hashlib
import importlib.util
import json
import struct
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Mapping


REPOSITORY = Path(__file__).resolve().parents[1]
CONTRACT_PATH = Path("qa/windows-ui-contract/msi-lifecycle-composition.json")
LEDGER_PATH = "qa/windows-ui-contract/material-rewrite-ledger.json"
ASSET_DIRECTORY = "instsetoo_native/inc_common/windows/msi_templates/Binary"
GENERATOR_PATH = REPOSITORY / "bin/generate-material-msi-branding.py"


class ValidationError(RuntimeError):
    pass


def _load_generator():
    spec = importlib.util.spec_from_file_location("material_msi_branding", GENERATOR_PATH)
    if spec is None or spec.loader is None:
        raise ValidationError(f"cannot load {GENERATOR_PATH}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


GENERATOR = _load_generator()


def _read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValidationError(f"{path}: root must be an object")
    return value


def _idt(text: str) -> tuple[list[str], list[dict[str, str]]]:
    lines = [line.rstrip("\r") for line in text.splitlines() if line]
    if len(lines) < 3:
        return [], []
    headers = lines[0].split("\t")
    rows: list[dict[str, str]] = []
    for line in lines[3:]:
        values = line.split("\t")
        values.extend([""] * (len(headers) - len(values)))
        rows.append(dict(zip(headers, values)))
    return headers, rows


def _bmp_header(payload: bytes) -> tuple[int, int, int]:
    if len(payload) < 54 or payload[:2] != b"BM":
        raise ValidationError("asset is not a Windows BMP")
    dib_size = struct.unpack_from("<I", payload, 14)[0]
    if dib_size != 40:
        raise ValidationError(f"unsupported BMP DIB header size {dib_size}")
    width, height = struct.unpack_from("<ii", payload, 18)
    bits_per_pixel = struct.unpack_from("<H", payload, 28)[0]
    return width, abs(height), bits_per_pixel


def violations(
    contract: Mapping[str, Any], texts: Mapping[str, str], binaries: Mapping[str, bytes]
) -> list[str]:
    errors: list[str] = []
    if contract.get("schema_version") != 1:
        errors.append("schema_version must be 1")
    if contract.get("contract") != "material-msi-lifecycle-composition":
        errors.append("contract marker drift")
    if contract.get("platform") != "windows":
        errors.append("platform must be windows")
    if contract.get("status") != "source-implemented":
        errors.append("status must be source-implemented")
    if contract.get("runtime_verified") is not False:
        errors.append("runtime_verified must remain false until a real MSI lifecycle passes")
    if (
        contract.get("surface") != "native:msi-install-lifecycle-ui"
        or contract.get("owner") != "instsetoo_native"
        or contract.get("inventory_id") != "WIN-SYS-013"
    ):
        errors.append("MSI lifecycle ownership drift")
    if contract.get("generator") != "bin/generate-material-msi-branding.py":
        errors.append("branding generator path drift")

    definition_path = str(contract.get("theme_definition"))
    try:
        definition = ET.fromstring(texts.get(definition_path, ""))
    except ET.ParseError as error:
        errors.append(f"Material definition XML failed: {error}")
        definition = None
    if definition is not None:
        palette = next(
            (item for item in definition.findall("palette") if not item.get("scheme")),
            None,
        )
        roles = {
            item.get("name")
            for item in palette.findall("color")
        } if palette is not None else set()
        for role in contract.get("token_roles", []):
            if role not in roles:
                errors.append(f"Material token role missing: {role}")

    generated = GENERATOR.generated_assets(REPOSITORY)
    assets = contract.get("assets")
    if not isinstance(assets, list) or len(assets) != 3:
        errors.append("exactly three bundled MSI branding assets are required")
        assets = []
    for asset in assets:
        if not isinstance(asset, Mapping):
            errors.append("asset entries must be objects")
            continue
        name = asset.get("name")
        payload = binaries.get(str(name))
        if payload is None:
            errors.append(f"bundled branding asset missing: {name}")
            continue
        if generated.get(str(name)) != payload:
            errors.append(f"{name}: generated bytes are stale")
        if hashlib.sha256(payload).hexdigest() != asset.get("sha256"):
            errors.append(f"{name}: sha256 drift")
        try:
            width, height, bits = _bmp_header(payload)
        except ValidationError as error:
            errors.append(f"{name}: {error}")
            continue
        if (width, height, bits) != (
            asset.get("width"),
            asset.get("height"),
            asset.get("bits_per_pixel"),
        ):
            errors.append(
                f"{name}: bitmap geometry is {(width, height, bits)}, expected "
                f"{(asset.get('width'), asset.get('height'), asset.get('bits_per_pixel'))}"
            )

    tables = contract.get("tables")
    if not isinstance(tables, Mapping):
        errors.append("tables must be an object")
        tables = {}
    table_rows: dict[str, list[dict[str, str]]] = {}
    for key, path in tables.items():
        if key == "custom_target":
            continue
        headers, rows = _idt(texts.get(str(path), ""))
        if not headers:
            errors.append(f"MSI table missing or malformed: {path}")
        table_rows[key] = rows

    binary_rows = {row.get("Name"): row for row in table_rows.get("binary", [])}
    for binary_id, asset_name in contract.get("binary_mappings", {}).items():
        row = binary_rows.get(binary_id)
        if row is None or row.get("Data") != asset_name:
            errors.append(f"Binary.idt lost {binary_id} -> {asset_name}")

    properties = {
        row.get("Property"): row.get("Value") for row in table_rows.get("property", [])
    }
    styles = {
        row.get("TextStyle"): row for row in table_rows.get("text_style", [])
    }
    font = contract.get("font_contract")
    if not isinstance(font, Mapping):
        errors.append("font_contract must be an object")
    else:
        if properties.get(font.get("default_property")) != font.get("default_style"):
            errors.append("MSI default UI font property drift")
        default_style = styles.get(font.get("default_style"))
        heading_style = styles.get(font.get("heading_style"))
        if not default_style or (
            default_style.get("FaceName"), default_style.get("Size")
        ) != (font.get("face"), font.get("size")):
            errors.append("MSI default Segoe UI style drift")
        if not heading_style or (
            heading_style.get("FaceName"), heading_style.get("Size"), heading_style.get("StyleBits")
        ) != (font.get("face"), font.get("heading_size"), "1"):
            errors.append("MSI heading style drift")

    dialogs = {row.get("Dialog"): row for row in table_rows.get("dialog", [])}
    controls = {
        (row.get("Dialog_"), row.get("Control")): row
        for row in table_rows.get("control", [])
    }
    stages = contract.get("lifecycle_dialogs")
    if not isinstance(stages, list) or len(stages) != 14:
        errors.append("lifecycle_dialogs must pin exactly fourteen stages")
        stages = []
    seen_stages: set[str] = set()
    for stage in stages:
        if not isinstance(stage, Mapping):
            errors.append("lifecycle dialog entries must be objects")
            continue
        stage_name = stage.get("stage")
        if not isinstance(stage_name, str) or stage_name in seen_stages:
            errors.append(f"duplicate or invalid lifecycle stage: {stage_name}")
        seen_stages.add(str(stage_name))
        dialog_name = stage.get("dialog")
        dialog = dialogs.get(dialog_name)
        if dialog is None:
            errors.append(f"lifecycle dialog missing: {dialog_name}")
            continue
        if dialog.get("Control_Default") != stage.get("default"):
            errors.append(f"{dialog_name}: default action drift")
        if dialog.get("Control_Cancel") != stage.get("cancel"):
            errors.append(f"{dialog_name}: cancel action drift")
        visual = controls.get((dialog_name, stage.get("visual_control")))
        if visual is None or visual.get("Type") != "Bitmap" or visual.get("Text") != stage.get("visual_binary"):
            errors.append(f"{dialog_name}: Material branding control drift")

    decisions = contract.get("decision_dialogs")
    if not isinstance(decisions, list) or len(decisions) != 3:
        errors.append("decision_dialogs must pin the three native decision surfaces")
        decisions = []
    for decision in decisions:
        if not isinstance(decision, Mapping):
            continue
        dialog_name = decision.get("dialog")
        dialog = dialogs.get(dialog_name)
        if dialog is None:
            errors.append(f"decision dialog missing: {dialog_name}")
            continue
        if dialog.get("Control_Default") != decision.get("safe_default"):
            errors.append(f"{dialog_name}: safe default drift")
        if dialog.get("Control_Cancel") != decision.get("cancel"):
            errors.append(f"{dialog_name}: cancel decision drift")

    custom_target = texts.get(str(tables.get("custom_target")), "")
    for marker in (
        "instsetoo_msi_templates:",
        "instsetoo_native/inc_common/windows/msi_templates/Binary/*.*",
        "copying binary assets",
    ):
        if marker not in custom_target:
            errors.append(f"MSI template-copy marker missing: {marker}")
    harness_path = str(contract.get("runtime_harness"))
    harness = texts.get(harness_path, "")
    for marker in ("old-install", "corrected-repair", "corrected-uninstall"):
        if marker not in harness:
            errors.append(f"runtime lifecycle harness marker missing: {marker}")

    owned = contract.get("os_owned_chrome")
    if not isinstance(owned, list) or len(set(owned)) != 5:
        errors.append("OS-owned installer chrome boundary drift")

    try:
        ledger = json.loads(texts.get(LEDGER_PATH, ""))
    except json.JSONDecodeError:
        errors.append("rewrite ledger is invalid JSON")
        ledger = {}
    row = next(
        (
            item
            for item in ledger.get("surfaces", [])
            if isinstance(item, Mapping) and item.get("surface") == contract.get("surface")
        ),
        None,
    )
    if row is None or row.get("owner") != "instsetoo_native" or row.get("family") != "native-shell":
        errors.append("MSI lifecycle ledger ownership drift")
    elif row.get("rewrite_status") == "rewritten-material":
        evidence = row.get("rewrite_evidence")
        markers = evidence.get("anatomy_markers") if isinstance(evidence, Mapping) else None
        if not isinstance(evidence, Mapping) or evidence.get("contract") != CONTRACT_PATH.as_posix():
            errors.append("rewritten MSI lifecycle row must cite its contract")
        if not isinstance(markers, Mapping) or markers.get("contract_marker") != contract.get("contract"):
            errors.append("rewritten MSI lifecycle row lost its contract marker")
    elif row.get("rewrite_status") != "pending":
        errors.append("MSI lifecycle ledger status must be pending or rewritten-material")
    return errors


def load_repository(
    repo: Path = REPOSITORY,
) -> tuple[dict[str, Any], dict[str, str], dict[str, bytes]]:
    contract = _read_json(repo / CONTRACT_PATH)
    text_paths = {
        str(contract.get("theme_definition")),
        str(contract.get("runtime_harness")),
        LEDGER_PATH,
    }
    tables = contract.get("tables")
    if isinstance(tables, Mapping):
        text_paths.update(str(path) for path in tables.values())
    texts = {
        relative: (repo / relative).read_text(encoding="utf-8")
        for relative in text_paths
        if relative and (repo / relative).is_file()
    }
    binaries = {
        str(asset.get("name")): (repo / ASSET_DIRECTORY / str(asset.get("name"))).read_bytes()
        for asset in contract.get("assets", [])
        if isinstance(asset, Mapping)
        and (repo / ASSET_DIRECTORY / str(asset.get("name"))).is_file()
    }
    return contract, texts, binaries


def validate(repo: Path = REPOSITORY) -> None:
    contract, texts, binaries = load_repository(repo)
    errors = violations(contract, texts, binaries)
    if errors:
        raise ValidationError("\n".join(errors))


def main() -> int:
    try:
        validate()
    except (OSError, json.JSONDecodeError, ET.ParseError, ValidationError) as error:
        print(f"MSI lifecycle composition contract failed:\n{error}", file=sys.stderr)
        return 1
    print(
        "MSI lifecycle composition passed: deterministic token-derived branding, fourteen lifecycle stages, "
        "three safe native decisions, Segoe hierarchy, template-copy path, and OS-owned chrome boundary are source-pinned; runtime lifecycle unverified."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
